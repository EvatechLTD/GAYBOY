"""Generate a constant-offset decoder without changing the battery format."""
from pathlib import Path
import re

source=Path('src/tones.c').read_text().split('static const ToneField tonefields[]={',1)[1].split('{0,0,0,0}',1)[0]
fields=re.findall(r'\{(.+?),\s*(\d+),\s*(\d+),\s*(\d+)\}',source)
assert len(fields)==416,len(fields)
lines=['/* Generated by tools/generate_tone_decoder.py. */','#pragma bank 42','#include "api.h"','uint8_t tone_fast_decode(void) BANKED __naked { __asm',' ld h,#1']
bit=raw=0
for index,(_,maximum,width,flags) in enumerate(fields):
 maximum,width,flags=map(int,(maximum,width,flags));label=f'tfd_{index}'
 def emit_byte(start,count,register):
  byte,shift=divmod(start,8);low=min(count,8-shift)
  lines.append(f' ld a,(0x{0xb871+byte:04x})')
  lines.extend([' rrca']*shift)
  lines.extend([f' and #{(1<<low)-1}',f' ld {register},a'])
  if low<count:
   lines.append(f' ld a,(0x{0xb872+byte:04x})')
   lines.extend([' rlca']*(8-shift))
   lines.extend([f' and #{((1<<(count-low))-1)<<low}',f' or a,{register}',f' ld {register},a'])
 emit_byte(bit,min(width,8),'c')
 if width>8:emit_byte(bit+8,width-8,'b')
 elif flags&1:lines.append(' ld b,#0')
 if maximum<(1<<width)-1:
  if width>8:
   lines.extend([' ld a,b',f' cp #{maximum>>8}',f' jr c,{label}_max$',f' jr nz,{label}_invalid$',' ld a,c',f' cp #{(maximum&255)+1}',f' jr c,{label}_max$'])
  else:lines.extend([' ld a,c',f' cp #{maximum+1}',f' jr c,{label}_max$'])
  lines.extend([f'{label}_invalid$:',' ld h,#0',f'{label}_max$:'])
 if flags&2:
  lines.append(' ld a,c')
  if flags&1:lines.append(' or a,b')
  else:lines.append(' or a,a')
  lines.extend([f' jr nz,{label}_nz$',' ld h,#0',f'{label}_nz$:'])
 if flags&4:
  lines.extend([' ld a,c',' sub a,#24',' ld c,a'])
  if flags&1:lines.extend([' ld a,b',' sbc a,#0',' ld b,a'])
 lines.extend([' ld a,c',f' ld (0x{0xba00+raw:04x}),a'])
 raw+=1
 if flags&1:lines.extend([' ld a,b',f' ld (0x{0xba00+raw:04x}),a']);raw+=1
 bit+=width
 if raw%8==0:lines.extend([' push hl',' call _mixfill',' pop hl'])
lines.extend([' ld a,h',' ret',' __endasm; }',''])
Path('build/tones_fast.c').write_text('\n'.join(lines))
print(f'{len(fields)} fields, {bit} packed bits, {raw} raw bytes -> build/tones_fast.c')
