"""Generate native patch scatter code from the existing prepared-state copy.

The persisted layout stays identical. Each critical window reads at most16
bytes from one physical page and restores RAM bank zero before audio service.
"""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
def generate():
 source=(ROOT/'src/tones.c').read_text()
 section=source.split('static void apply_prepared(void)',1)[1].split('static void finalize_prepared(void)',1)[0]
 fields=[(address.strip(),int(size)) for address,size in re.findall(r'ld hl,#([^\n]+)\n\s*\.rept (\d+)',section)]
 assert sum(size for _,size in fields)==442
 fields.append(('_pulsekickpatch',8))
 positions=[]
 for address,size in fields:
  for offset in range(size):positions.append((address,offset))
 assert len(positions)==450
 noise=[i for i,(address,_) in enumerate(positions) if address=='_noisepatch']
 assert noise==list(range(425,435))
 symbols=sorted({re.match(r'_[A-Za-z0-9_]+',address)[0] for address,_ in fields})
 out=['/* Generated by tools/generate_native_scatter.py; native patch layout unchanged. */','#pragma bank 48','#include "api.h"','#include "tones.h"',
 '/* Native pulse/PCM audio is IRQ-owned. EI/NOP between windows lets it',
 '   run with bank zero restored while MIDI and sequencing stay queued. */',
 '/* Near ABI: page map in DE. Local stack is bank byte then map pointer. */',
 'static void native_scatter(uint8_t *map) __naked {__asm']
 out += [' .globl '+symbol for symbol in symbols]
 out += [' push de',' push af',' inc sp']
 def map_pointer():out.extend([' ldhl sp,#1',' ld a,(hl+)',' ld h,(hl)',' ld l,a'])
 raw=0
 for page in range(8):
  length=min(56 if page==0 else 62,450-raw)
  if not length:break
  out.append(f'; Physical source span {page}; raw bytes {raw}..{raw+length-1}.')
  map_pointer()
  if page:out.extend([f' ld bc,#{page*3}',' add hl,bc'])
  out.extend([' ld a,(hl+)',' ld e,a',' ld a,(hl+)',' ld d,a',' ld a,(hl)',' ldhl sp,#0',' ld (hl),a'])
  end=raw+length
  while raw<end:
   noise_window=425<=raw<435
   stop=min(raw+16,end,435 if noise_window else 425 if raw<425 else 450)
   out.extend([' di',' ldhl sp,#0',' ld a,(hl)',' ld (0x4000),a',' ld a,#0x0a',' ld (0x0000),a'])
   if noise_window:
    map_pointer()
    if raw>425:out.extend([f' ld bc,#{raw-425}',' add hl,bc'])
    out.append(f' .rept {stop-raw}')
    out.extend([' ld a,(de)',' inc de',' ld (hl+),a',' .endm'])
   else:
    at=raw
    while at<stop:
     address,offset=positions[at];run=1
     while at+run<stop and positions[at+run]==(address,offset+run):run+=1
     target=address+(f'+{offset}' if offset else '')
     out.extend([' ld hl,#'+target,f' .rept {run}',' ld a,(de)',' inc de',' ld (hl+),a',' .endm'])
     at+=run
   out.extend([' xor a,a',' ld (0x4000),a',' ei',' nop'])
   raw=stop
 assert raw==450
 out.append('; Map entries zero through three are consumed; their bytes hold noise.')
 map_pointer();out.extend([' ld d,h',' ld e,l',' ld hl,#_noisepatch',' .rept 10',' ld a,(de)',' inc de',' ld (hl+),a',' .endm',' add sp,#3',' ret',' __endasm;}'])
 out.extend(['uint8_t tones_scatter_object(uint16_t object) BANKED {uint8_t map[24];',
 ' if(monomode||experimental_mode||(waveengine&&waveengine!=3))return 0;',
 ' if(!sparse_prepared_map(object,map)&&!pool_native_map(object,map))return 0;',
 ' /* Mapping can service queued MIDI that changes the active engine. */',
 ' if(monomode||experimental_mode||(waveengine&&waveengine!=3))return 0;',
 ' native_scatter(map);return 1;',
 '}',
 'uint8_t tones_apply_object(uint16_t object) BANKED {',
 ' /* Software engines retain their existing coherent RAW application path. */',
 ' if(monomode||experimental_mode||(waveengine&&waveengine!=3))goto raw;',
 ' if(!tones_scatter_object(object)){',
 '  if(monomode||experimental_mode||(waveengine&&waveengine!=3))goto raw;',
 '  return 0;',
 ' }',
 ' tones_finalize();return 1;',
 'raw:',
 ' if(!pool_object_read(object,0,TONE_RAW,450))return 0;',
 ' memcpy(TONE_KICK_RAW,TONE_RAW+TONE_RAW_BYTES,8);tones_apply();return 1;',
 '}',''])
 (ROOT/'src/tones_native.c').write_text('\n'.join(out))
if __name__=='__main__':generate()
