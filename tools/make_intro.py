tiles, lookup = [], {}

def tile(im):
    data = []
    for y in range(8):
        row = sum((im.getpixel((x, y)) != 0) << (7-x) for x in range(8))
        data.extend((row, row))
    key = bytes(data)
    if key not in lookup:
        lookup[key] = len(tiles)
        tiles.append(key)
    return lookup[key]

