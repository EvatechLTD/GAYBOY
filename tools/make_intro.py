glyphs = next(eval(compile(ast.Expression(n.value), '<local font>', 'eval'), {'__builtins__': {}}) for n in tree.body
              if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'glyphs' for t in n.targets))
tiles, lookup = [], {}

def tile(im):
    data = []
    for y in range(8):
        row = sum((im.getpixel((x, y)) != 0) << (7-x) for x in range(8))
        data.extend((row, row))
    key = bytes(data)
    if key not in lookup:
        lookup[key] = len(tiles)
        tiles.append(key)
    return lookup[key]

blank = tile(Image.new('1', (8, 8)))
phrases = ['press play']
text_maps = []
for phrase in phrases:
    prefixes = []
    for count in range(26):
        im = Image.new('1', (160, 8))
        left = (160 - (len(phrase)*8-1)) // 2
        for index, c in enumerate(phrase[:count]):
            for y, row in enumerate(glyphs.get(c.upper(), ['00000'] * 7)):
                for x, v in enumerate(row):
                    if v == '1': im.putpixel((left+index*8+x, y), 1)
        prefixes.append([tile(im.crop((x, 0, x+8, 8))) for x in range(0, 160, 8)])
    text_maps.append(prefixes)

maps = []
for mood in range(7):
    im = Image.new('1', (160, 144))
    d = ImageDraw.Draw(im)
    # The hardware is the enclosure: the entire display is BMO's face.
    for x in (45, 115):
        if mood == 1: d.rounded_rectangle((x-11, 35, x+11, 40), radius=2, fill=1)
        elif mood == 3 and x == 115: d.arc((x-12, 26, x+12, 50), 180, 355, fill=1, width=4)
        elif mood == 4: d.arc((x-12, 26, x+12, 50), 185, 355, fill=1, width=4)
        else: d.ellipse((x-9, 23 if mood != 2 else 20, x+9, 51), fill=1)
    if mood == 2: d.ellipse((68, 59, 92, 89), fill=1)
    elif mood == 5:
        d.rounded_rectangle((56, 59, 104, 92), radius=12, fill=1)
        d.rectangle((63, 59, 97, 64), fill=0)
    elif mood == 6: d.line((64, 77, 96, 77), fill=1, width=4)
    else: d.arc((51, 43, 109, 90), 0, 180, fill=1, width=4)
    # Place the face's visual bounds around the display's vertical midpoint.
    centered = Image.new('1', (160, 144))
    centered.paste(im, (0, 18))
    maps.append([tile(centered.crop((x, y, x+8, y+8))) for y in range(0, 144, 8) for x in range(0, 160, 8)])
