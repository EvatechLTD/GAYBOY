def fade_tiles(im,level):
    data=[]
    for ty in range(0,im.height,8):
        for tx in range(0,160,8):
            for yy in range(8):
                colors=[(im.getpixel((tx+xx,ty+yy))*level+2)//3 for xx in range(8)]
                data.extend((sum((c&1)<<(7-x) for x,c in enumerate(colors)),sum(((c>>1)&1)<<(7-x) for x,c in enumerate(colors))))
    return data
