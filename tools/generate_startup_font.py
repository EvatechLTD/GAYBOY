"""Expand the existing packed UI font into byte-identical startup ROM tiles."""
from hashlib import sha256
from pathlib import Path
import re

GRAY = '0123456789ACDEIKLNRSTUY'


def tiles(source):
    packed = bytes(map(int, re.search(r'ui_glyphs\[\]\s*=\s*\{([^}]+)\}',
                                     source.read_text()).group(1).split(',')))

    def glyph(c):
        # Independent bit-string extraction also checks the original C
        # packed-word/shift calculation for every generated glyph row.
        bits = ''.join(f'{byte:08b}'[::-1] for byte in packed)
        rows = []
        for y in range(8):
            old = 0
            if c < 64 and y < 7:
                bit = (c * 7 + y) * 5
                old = (((packed[bit >> 3] | packed[(bit >> 3) + 1] << 8)
                        >> (bit & 7)) & 31) << 2
                assert old == int(bits[bit:bit + 5][::-1], 2) << 2
            rows.append(old)
        return rows

    base = bytearray()
    for tile in range(192):
        for value in glyph(tile % 96):
            if tile >= 96:
                value ^= 255
            base.extend((value, value))
    gray = bytearray()
    for character in GRAY:
        for value in glyph(ord(character) - 32):
            gray.extend((value, 0))
    widgets = bytearray()
    for tile in range(12):
        for y in range(8):
            value = (126 if y + tile >= 8 else 0) if tile < 9 else (
                (255 if y == 3 else 0) if tile == 9 else (
                    126 if y in (1, 6) else (126 if tile == 11 else 66) if 1 < y < 6 else 0))
            widgets.extend((value, 0 if tile == 9 else value))
    assert len(base) + len(gray) + len(widgets) == 3632
    return bytes(base), bytes(gray), bytes(widgets)


def generate(source, output):
    arrays = tiles(source)
    lines = ['/* Generated by tools/generate_startup_font.py; do not edit. */',
             f'static const char startup_graychars[]="{GRAY}";']
    for name, data in zip(('base', 'gray', 'widgets'), arrays):
        lines.append(f'static const uint8_t startup_font_{name}[]={{')
        lines.extend(','.join(map(str, data[at:at + 32])) + ',' for at in range(0, len(data), 32))
        lines.append('};')
    result = '\n'.join(lines) + '\n'
    if not output.exists() or output.read_text() != result:
        output.write_text(result)
    return sha256(b''.join(arrays)).hexdigest()


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    print(generate(root / 'src/ui_tiles.h', root / 'src/ui_startup_font.h'))
